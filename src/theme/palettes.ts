export type HexColor = `#${string}`;
export type Shade = 100 | 200 | 300 | 400 | 500 | 600 | 700 | 800 | 900;

export type ColorScale = {
  name: string;
  DEFAULT: HexColor;
} & Record<Shade, HexColor>;

export const paletteRoleOrder = [
  "primaryDark",
  "primaryLight",
  "base",
  "secondaryLight",
  "secondaryDark",
] as const;

export type PaletteRole = (typeof paletteRoleOrder)[number];

export type PaletteSource = {
  label: string;
  description: string;
  colors: Record<PaletteRole, ColorScale>;
};

type ScaleShades = readonly [
  HexColor,
  HexColor,
  HexColor,
  HexColor,
  HexColor,
  HexColor,
  HexColor,
  HexColor,
  HexColor,
];

function scale(
  name: string,
  defaultValue: HexColor,
  shades: ScaleShades,
): ColorScale {
  return {
    name,
    DEFAULT: defaultValue,
    100: shades[0],
    200: shades[1],
    300: shades[2],
    400: shades[3],
    500: shades[4],
    600: shades[5],
    700: shades[6],
    800: shades[7],
    900: shades[8],
  };
}

